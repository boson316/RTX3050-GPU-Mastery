"""
Run every CUDA roadmap benchmark, check that each kernel passed its built-in verification,
and print a summary table (also written to cuda_roadmap/results.md).

Build first:   cd cuda_roadmap && ./build.sh        (Windows: build.bat)
Run:           python cuda_roadmap/run_benchmarks.py

Each benchmark binary prints KEY=VALUE lines (see common/bench_common.cuh):
  VERIFY_<variant>=PASS|FAIL, CUDA_NAIVE_MS, CUDA_OPTIMIZED_MS, *_GBPS, *_GFLOPS ...
Timings are medians of 20 CUDA-event-timed runs after warm-up.
Exit code is non-zero if any binary fails, is missing, or reports VERIFY_*=FAIL.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent

# (title, binary path without extension, metric key suffix shown next to the timings)
BENCHMARKS = [
    ("L1 vector add (float vs float4)", "level1_basics/vector_add/vector_add_bench", "GBPS"),
    ("L1 reduction (atomic vs smem tree)", "level1_basics/reduction/reduction_bench", "GBPS"),
    ("L1 naive SGEMM 1024^3", "level1_basics/naive_matmul/naive_matmul_bench", "GFLOPS"),
    ("L2 tiled SGEMM 1024^3", "level2_memory/tiled_matmul/tiled_matmul_bench", "GFLOPS"),
    ("L2 coalescing (strided vs coalesced copy)", "level2_memory/coalescing/coalescing_bench", "GBPS"),
    ("L2 bank conflicts (transpose [32][32] vs [32][33])", "level2_memory/bank_conflict/bank_conflict_bench", "GBPS"),
    ("L3 reduction (smem tree vs warp shuffle)", "level3_advanced/warp_shuffle_reduction/warp_shuffle_bench", "GBPS"),
    ("L3 fusion (add;relu vs add+relu)", "level3_advanced/fused_ops/fused_ops_bench", "GBPS"),
    ("L3 grid-stride / persistent", "level3_advanced/persistent_kernel/persistent_kernel_bench", "GBPS"),
    ("L4 FP16 GEMM 1024^3 (CUDA cores vs WMMA tiled)", "level4_tensor_core/fp16_tensor_core_matmul/fp16_matmul_bench", "GFLOPS"),
    ("L4 WMMA 16x16x16 example", "level4_tensor_core/wmma_example/wmma_example", ""),
]


def run_exe(stem: Path) -> tuple[dict[str, str], str | None]:
    exe = stem if stem.is_file() else stem.with_suffix(".exe")
    if not exe.is_file():
        return {}, f"not built ({stem.name})"
    try:
        proc = subprocess.run([str(exe)], cwd=exe.parent, capture_output=True, text=True, timeout=300)
    except Exception as e:  # noqa: BLE001
        return {}, str(e)
    kv = {}
    for line in proc.stdout.splitlines():
        for token in line.split():
            if "=" in token:
                k, v = token.split("=", 1)
                kv[k.strip()] = v.strip()
    if proc.returncode != 0:
        return kv, f"exit code {proc.returncode}: {proc.stderr.strip()[:200]}"
    return kv, None


def fmt(kv: dict[str, str], key: str) -> str:
    try:
        return f"{float(kv[key]):.4f}"
    except (KeyError, ValueError):
        return "-"


def main() -> int:
    rows, failed = [], False
    for title, rel, metric in BENCHMARKS:
        kv, err = run_exe(ROOT / rel)
        verify = [v for k, v in kv.items() if k.startswith("VERIFY")]
        status = "PASS" if verify and all(v == "PASS" for v in verify) and err is None else "FAIL"
        if err or status != "PASS":
            failed = True
        naive, opt = fmt(kv, "CUDA_NAIVE_MS"), fmt(kv, "CUDA_OPTIMIZED_MS")
        speedup = f"{float(naive) / float(opt):.2f}x" if "-" not in (naive, opt) and float(opt) > 0 else "-"
        m_naive = kv.get(f"NAIVE_{metric}", "-") if metric else "-"
        m_opt = kv.get(f"OPTIMIZED_{metric}", kv.get(f"WMMA_TILED_{metric}", "-")) if metric else "-"
        extra = f"{kv['WMMA_TILED_PCT_OF_CUBLAS']}% of cuBLAS" if "WMMA_TILED_PCT_OF_CUBLAS" in kv else ""
        rows.append((title, status if not err else f"ERROR: {err}", naive, opt, speedup,
                     f"{m_naive} -> {m_opt} {metric}" if metric else "", extra))

    header = "| Benchmark | Verify | Naive (ms) | Optimized (ms) | Speedup | Throughput | Notes |"
    lines = [header, "|" + "---|" * 7] + ["| " + " | ".join(r) + " |" for r in rows]
    table = "\n".join(lines)
    print(table)
    (ROOT / "results.md").write_text(
        "# CUDA roadmap results\n\nGenerated by `python cuda_roadmap/run_benchmarks.py` "
        "(median of 20 runs after warm-up; every kernel verified against a CPU reference).\n\n" + table + "\n",
        encoding="utf-8",
    )
    print(f"\nWritten to {ROOT / 'results.md'}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
